import { CLOUDFLARE_LIVE_CLIENT_V26 } from './cloudflare-live-client-v26.js';

function replaceOnce(source, target, replacement, label) {
  if (!source.includes(target)) throw new Error(`TalkSys v30 client patch target missing: ${label}`);
  return source.replace(target, replacement);
}

let source = CLOUDFLARE_LIVE_CLIENT_V26;

source = replaceOnce(
  source,
  "  const AGENT_PATH = '/agents/talk-sys-voice-agent/default';\n",
  "  const AGENT_PATH = '/agents/talk-sys-voice-agent/default';\n  const GROK_TTS_ENDPOINT = '/api/grok-tts-v30';\n",
  'Grok TTS endpoint',
);

source = replaceOnce(
  source,
  "  let ttsFallbackTimer = null;\n",
  "  let ttsFallbackTimer = null;\n  let typedTtsGeneration = 0;\n  let grokAudioBytes = 0;\n  let grokAudioChunks = 0;\n  let grokAudioLastAt = 0;\n  let grokTtsRequests = 0;\n",
  'Grok audio diagnostics state',
);

source = replaceOnce(
  source,
  "  try { window.__talksysVoiceDebug = () => microphoneDiagnostics(); } catch {}\n",
  `  try {
    window.__talksysVoiceDebug = () => ({
      ...microphoneDiagnostics(),
      ttsProvider: 'xai/grok-tts',
      browserSpeechSynthesisEnabled: false,
      grokAudioBytes,
      grokAudioChunks,
      grokAudioLastAt,
      grokTtsRequests,
      typedVoiceOutput,
    });
  } catch {}
`,
  'combined audio diagnostics',
);

// v24 tried to reduce latency by speaking completed answer sentences with the
// browser's local voice. That made the device voice audible and then caused the
// real server audio to be discarded. v30 makes Grok TTS the only answer voice.
source = source.replace(/\n\s*queueCompletedStreamSpeech\(streamText, false\);/g, '');
source = source.replace(/\n\s*queueCompletedStreamSpeech\(value, true\);/g, '');

source = replaceOnce(
  source,
  "    if (browserStreamTtsThisTurn) return;\n    serverAudioThisTurn = true;\n",
  `    browserStreamTtsThisTurn = false;
    serverAudioThisTurn = true;
    const byteLength = Number(buffer?.byteLength || 0);
    grokAudioBytes += byteLength;
    grokAudioChunks += 1;
    grokAudioLastAt = Date.now();
    dispatch('talksys-grok-audio', { bytes: byteLength, totalBytes: grokAudioBytes, chunks: grokAudioChunks });
`,
  'never discard Grok server audio',
);

source = replaceOnce(
  source,
  "  function speakJapaneseFallback(text, purpose = 'answer') {\n",
  `  function speakJapaneseFallback(text, purpose = 'answer') {
    // Browser/device speech is deliberately disabled. Audible responses are
    // generated by xai/grok-tts so Android, desktop and typed simulation use
    // the same voice.
    return false;
`,
  'disable browser speech synthesis fallback',
);

source = replaceOnce(
  source,
  "  function finishAssistantStream(finalText) {\n",
  `  async function requestTypedGrokTts(text, generation) {
    const value = String(text || '').trim();
    if (!value || desiredCall || !typedVoiceOutput) return;
    grokTtsRequests += 1;
    try {
      const response = await fetch(GROK_TTS_ENDPOINT, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ text: value }),
      });
      if (!response.ok) throw new Error('Grok TTS HTTP ' + response.status);
      const buffer = await response.arrayBuffer();
      if (!buffer.byteLength) throw new Error('Grok TTS returned empty audio');
      if (generation !== typedTtsGeneration || desiredCall || !typedVoiceOutput || serverAudioThisTurn) return;
      queueAudio(buffer);
      dispatch('talksys-typed-grok-tts', { bytes: buffer.byteLength, generation });
    } catch (error) {
      if (generation !== typedTtsGeneration) return;
      setStatus('Grok音声を生成できませんでした。文字回答は利用できます。');
      dispatch('talksys-grok-tts-error', { message: String(error?.message || error).slice(0, 180) });
    }
  }

  function finishAssistantStream(finalText) {
`,
  'typed Grok TTS requester',
);

source = replaceOnce(
  source,
  `    clearTimeout(ttsFallbackTimer);
    ttsFallbackTimer = null;
    if ((desiredCall || typedVoiceOutput) && !serverAudioThisTurn && value) {
      ttsFallbackTimer = setTimeout(() => {
        ttsFallbackTimer = null;
        if (!serverAudioThisTurn && !playing && !deviceSpeaking) speakJapaneseFallback(value);
      }, 500);
    }
`,
  `    clearTimeout(ttsFallbackTimer);
    ttsFallbackTimer = null;
    if (typedVoiceOutput && !desiredCall && !serverAudioThisTurn && value) {
      const generation = typedTtsGeneration;
      void requestTypedGrokTts(value, generation);
    }
`,
  'typed responses use Grok TTS rather than device voice',
);

source = replaceOnce(
  source,
  `    typedVoiceOutput = true;
    serverAudioThisTurn = false;
`,
  `    typedVoiceOutput = true;
    typedTtsGeneration += 1;
    stopPlayback(true);
    serverAudioThisTurn = false;
`,
  'typed turn resets prior audio',
);

source = replaceOnce(
  source,
  `  if ('speechSynthesis' in window) {
    try { speechSynthesis.getVoices(); } catch {}
    window.addEventListener('voiceschanged', () => { try { speechSynthesis.getVoices(); } catch {} });
  }
`,
  `  // Intentionally do not initialize browser speech synthesis in v30.
`,
  'no browser voice initialization',
);

export const CLOUDFLARE_LIVE_CLIENT_V30 = source;
